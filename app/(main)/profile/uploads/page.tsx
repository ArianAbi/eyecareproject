import { requireUser } from "@/lib/access";
import prisma from "@/lib/db";
import UploadList from "./UploadList";
export default async function UploadsPage() {
  const user = await requireUser();
  const assets = await prisma.imageAsset.findMany({ where: { ownerId: user.id }, orderBy: { createdAt: "desc" }, take: 100 });
  return <div className="space-y-4"><h1>?????? ????????????</h1><p>?????? ?????????? ?? ??? ???? ?? ???? ???? ???? ???.</p><UploadList assets={assets.map(asset => ({ filename: asset.filename, size: asset.size }))} /></div>;
}
